from dataclasses import dataclass
from datetime import date


def is_simulated_obs_id(obs_id: str) -> bool:
    """True for observation IDs minted by the offline demo fallback.

    Real SPHEREx exposure IDs look like ``2025W19_1B_0231_3``. The fallback
    mints ``spherex_<release>_<ra>_<dec>_pass<N>_b<band>`` so it can be told
    apart from archive records even after a round-trip through a cache.
    """
    return obs_id.startswith("spherex_") and "_pass" in obs_id


@dataclass(frozen=True)
class Observation:
    id: str
    region_id: str
    epoch_mjd: float        # Modified Julian Date
    band_index: int         # 0-101 (SPHEREx bands)
    wavelength_um: float    # 0.75-5.0 micrometers
    fits_url: str           # IRSA IBE direct URL
    quality_pct: float      # 0-100 (% clean pixels)
    data_release: str       # "qr3"
    obs_date: date
    ra: float
    dec: float
    # True when this record was generated by the offline demo fallback rather
    # than returned by the IRSA archive.
    is_simulated: bool = False
